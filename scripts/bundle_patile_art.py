#!/usr/bin/env python3
"""Embed the two Patile drawing atlases for origin-clean canvas use from file://."""
import argparse
import base64
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'sprite_preview' / 'patilife_v2'

def content():
    data = {name: 'data:image/png;base64,' + base64.b64encode((BASE / 'assets' / file).read_bytes()).decode('ascii') for name, file in [('controls', 'patile-control-icons.png'), ('pieces', 'patile-piece-sprites.png')]}
    return '/* Generated by scripts/bundle_patile_art.py. Local-file-safe drawing sources. */\nwindow.PatiLifePatileArt=Object.freeze(' + json.dumps(data, separators=(',', ':')) + ');\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = BASE / 'patile-art-data.js'
    expected = content()
    if args.check:
        if not target.exists() or target.read_text() != expected:
            raise SystemExit('Patile art bundle is stale; run python3 scripts/bundle_patile_art.py')
    else:
        target.write_text(expected)
    print('Patile local artwork bundle verified.')
